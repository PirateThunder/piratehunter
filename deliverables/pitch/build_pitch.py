def shp(slide, sid):
    return next(s for s in slide.shapes if s.shape_id == sid)


def set_text(shape, text):
    shape.text_frame.text = text


def set_run(shape, p, r, text):
    shape.text_frame.paragraphs[p].runs[r].text = text


def notes(slide, text):
    slide.notes_slide.notes_text_frame.text = text


def style_runs(shape, color=None, bold=None, size=None):
    for para in shape.text_frame.paragraphs:
        for run in para.runs:
            if color is not None:
                run.font.color.theme_color = color
            if bold is not None:
                run.font.bold = bold
            if size is not None:
                run.font.size = Pt(size)


def set_card(shape, head, body):
    """Два абзаца: заголовок жирный акцентом, деталь обычным."""
    tf = shape.text_frame
    tf.text = f'{head}\n{body}'
    for run in tf.paragraphs[0].runs:
        run.font.bold = True
        run.font.color.theme_color = ACC5
    for run in tf.paragraphs[1].runs:
        run.font.color.theme_color = TX1


def add_textbox(slide, l, t, w, h, text, color=None, bold=False, size=14,
                align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    tb = slide.shapes.add_textbox(Emu(l), Emu(t), Emu(w), Emu(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.text = text
    for para in tf.paragraphs:
        para.alignment = align
    style_runs(tb, color=color, bold=bold, size=size)
    return tb

